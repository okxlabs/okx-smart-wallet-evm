# Check the owner balance
cast balance 0xBb6e024b9cFFACB947A71991E386681B1Cd1477D --rpc-url $RPC_URL
# Check if the owner balance is zero, and fund it if needed
OWNER_ADDRESS="0xBb6e024b9cFFACB947A71991E386681B1Cd1477D"
OWNER_BALANCE=$(cast balance $OWNER_ADDRESS --rpc-url $RPC_URL)
# Remove possible whitespace and leading zeros
OWNER_BALANCE_CLEAN=$(echo $OWNER_BALANCE | tr -d '[:space:]')
if [ "$OWNER_BALANCE_CLEAN" = "0" ] || [ "$OWNER_BALANCE_CLEAN" = "0x0" ]; then
  # Send 1 ether from the default anvil account to the owner address
  # The default anvil private key is used here for local testing
  echo "Owner balance is zero. Funding $OWNER_ADDRESS with 1 ether..."
  cast send --rpc-url $RPC_URL \
    --private-key $DEPLOYER_PRIVATE_KEY \
    --value 1ether \
    $OWNER_ADDRESS
else
  echo "Owner balance is nonzero: $OWNER_BALANCE"
fi

# Check the deployFactory code
cast code 0xce0042B868300000d44A59004Da54A005ffdcf9f --rpc-url $RPC_URL
# Deploy the DeployFactory contract
cast publish $CALLDATA --rpc-url $RPC_URL
